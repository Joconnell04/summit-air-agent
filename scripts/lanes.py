"""Write docs/ai-process/lanes.md from GitHub: one row per lane issue (label `agent`), with its pull
requests and decisions. The brief links here instead of keeping its own copy, so the two can't drift.

Run with `make lanes`. Needs the `gh` CLI, signed in.
"""

import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "ai-process" / "lanes.md"
REPO = "Joconnell04/summit-air-agent"
PR_URL = f"https://github.com/{REPO}/pull/"
ISSUE_URL = f"https://github.com/{REPO}/issues/"

HEADER = """# Lanes

Generated by `make lanes` from GitHub; don't edit by hand. Each build lane has an issue labeled
`agent`; its pull requests close it. Lanes started from a chat request before this rule had their
issue backfilled (the issue body says so).
"""


def _gh(*args: str) -> list[dict]:
    out = subprocess.run(["gh", *args, "-R", REPO], capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def pr_numbers(body: str) -> list[int]:
    """Pull requests listed in an issue body as `- #NN title` lines, in order."""
    return [int(n) for n in re.findall(r"^- #(\d+)\b", body, flags=re.MULTILINE)]


def decisions(body: str) -> str:
    match = re.search(r"\*\*Decisions?:\*\*\s*DECISIONS\.md\s*(.+)", body)
    return match.group(1).strip() if match else ""


def render(issues: list[dict], pr_state: dict[int, str]) -> str:
    def row(issue: dict) -> str:
        prs = pr_numbers(issue["body"])
        cells = []
        for n in prs:
            mark = "" if pr_state.get(n, "MERGED") == "MERGED" else f" ({pr_state[n].lower()})"
            cells.append(f"[#{n}]({PR_URL}{n}){mark}")
        num = issue["number"]
        return f"| [#{num}]({ISSUE_URL}{num}) | {issue['title']} | {', '.join(cells) or ('none yet' if issue['state'] == 'OPEN' else 'see issue')} | {decisions(issue['body'])} |"

    table_head = "| Issue | Lane | Pull requests | Decisions |\n|---|---|---|---|"
    open_rows = [row(i) for i in sorted(issues, key=lambda i: i["number"]) if i["state"] == "OPEN"]
    done_rows = [row(i) for i in sorted(issues, key=lambda i: -i["number"]) if i["state"] != "OPEN"]
    parts = [HEADER, "## Open\n", table_head, *(open_rows or ["| | none | | |"]), "", "## Done, newest first\n", table_head, *done_rows]
    return "\n".join(parts) + "\n"


def main() -> None:
    issues = _gh("issue", "list", "--label", "agent", "--state", "all", "--limit", "200", "--json", "number,title,state,body")
    prs = _gh("pr", "list", "--state", "all", "--limit", "300", "--json", "number,state")
    OUT.write_text(render(issues, {p["number"]: p["state"] for p in prs}))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(issues)} lanes)")


if __name__ == "__main__":
    main()
