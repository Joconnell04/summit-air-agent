"""The interface between the tool server and a company's field service system.

It holds only the calls the tools need. There is no method that deletes, bulk-changes or runs a
free-form query, so no tool can do those whatever the model asks (spec S-39). Moving to another
system (or to real ServiceTitan) means a new adapter, not new tools.

Replies keep the field service system's own shapes (ServiceTitan's names), so the tool server reads
them as they are; the company's rules on top of them live in the tool server.
"""

import contextvars
from datetime import datetime
from typing import Protocol

# Each FSM request made while handling one tool call, for the stage timings in the log.
fsm_timings: contextvars.ContextVar[list | None] = contextvars.ContextVar(
    "fsm_timings", default=None
)


class FsmUnavailable(Exception):
    """The FSM could not be reached, timed out, or failed on its side. The request may be retried."""


class FsmRejected(Exception):
    """The FSM refused the request by its own rules (a taken slot, an unknown id, ...). code is the
    adapter's name for what the status means: slot_taken (409), not_found (404), unauthorized
    (401, 403) or rejected."""

    def __init__(self, status: int, code: str, detail: str):
        super().__init__(f"{status} {code}: {detail}")
        self.status = status
        self.code = code
        self.detail = detail


class FsmAdapter(Protocol):
    # Reads
    def customers_by_phone(self, phone: str) -> list[dict]: ...
    def locations_by_address(self, street: str, zip_code: str, unit: str | None) -> list[dict]: ...
    def customer(self, customer_id: int) -> dict: ...
    def contacts(self, customer_id: int) -> list[dict]: ...
    def locations(self, customer_id: int, include_inactive: bool = False) -> list[dict]: ...
    def location(self, location_id: int) -> dict: ...
    def memberships(self, customer_id: int) -> list[dict]: ...
    def jobs(self, customer_id: int, statuses: list[str] | None = None) -> list[dict]: ...
    def job(self, job_id: int) -> dict: ...
    def appointments(self, job_id: int) -> list[dict]: ...
    def job_notes(self, job_id: int) -> list[dict]: ...
    def notes(self, customer_id: int) -> list[dict]: ...
    def equipment(self, customer_id: int, location_ids: list[int] | None = None) -> list[dict]: ...
    def capacity(
        self, start: datetime, end: datetime, business_unit_id: int, job_type_id: int
    ) -> list[dict]: ...
    def find_job(self, customer_id: int, key: str) -> dict | None: ...
    def health(self) -> bool: ...

    # The schedule, for the owner view and the bench (app/schedule.py)
    def customers_by_name(self, name: str) -> list[dict]: ...
    def technicians(self) -> list[dict]: ...
    def appointments_between(self, start: datetime, end: datetime) -> list[dict]: ...
    def assignments(self, appointment_ids: list[int]) -> list[dict]: ...
    def non_job_appointments(self, start: datetime, end: datetime) -> list[dict]: ...

    # The call log: ServiceTitan's phone system writes it, the adapter reads it and tags calls
    def calls_from(self, phone: str, since: datetime | None = None) -> list[dict]: ...
    def calls_to(self, phone: str, since: datetime | None = None) -> list[dict]: ...
    def find_call(self, sid: str) -> dict | None: ...
    def find_outbound_call(self, sid: str, phone: str, started: datetime) -> dict | None: ...
    def tag_call(self, call_id: int, tag: str) -> dict: ...
    def record_outbound_call(
        self,
        sid: str,
        from_number: str,
        to_number: str,
        started: datetime,
        seconds: int,
        customer_id: int | None = None,
    ) -> None: ...

    # Writes. The key identifies the attempt on our side: ServiceTitan has no idempotency, so a
    # retry with the same key finds what the first attempt made (find_job) instead of making it again.
    def create_customer(
        self, key: str, name: str, address: dict, phone: str, contact_name: str | None = None
    ) -> dict: ...
    def create_location(self, key: str, customer_id: int, address: dict) -> dict: ...
    def set_location_active(self, key: str, location_id: int, active: bool) -> dict: ...
    def move_job(self, key: str, job_id: int, location_id: int) -> dict: ...
    def create_job(
        self,
        key: str,
        customer_id: int,
        location_id: int,
        business_unit_id: int,
        job_type_id: int,
        priority: str,
        campaign_id: int,
        summary: str,
        window_start: datetime,
        window_end: datetime,
        technician_ids: list[int] | None = None,
    ) -> dict: ...
    def reschedule(
        self,
        key: str,
        appointment_id: int,
        window_start: datetime,
        window_end: datetime,
        technician_id: int | None = None,
    ) -> dict: ...
    def cancel_job(self, key: str, job_id: int, reason_id: int, memo: str) -> dict: ...
    def create_lead(self, key: str, lead: dict) -> dict: ...
    def add_note(
        self, key: str, customer_id: int, text: str, job_id: int | None = None, pin: bool = False
    ) -> dict: ...

    # Edits a person makes on the owner view or the bench (app/schedule.py). Each changes one
    # record; a block is taken off the schedule, never deleted.
    def create_non_job_appointment(
        self, key: str, technician_id: int, start: datetime, end: datetime, name: str, summary: str
    ) -> dict: ...
    def end_non_job_appointment(self, key: str, non_job_id: int) -> dict: ...
    def change_job(self, key: str, job_id: int, changes: dict) -> dict: ...
    def correct_location_address(self, key: str, location_id: int, address: dict) -> dict: ...
    def rename_customer(self, key: str, customer_id: int, name: str) -> dict: ...
    def change_phone(self, key: str, customer_id: int, contact_id: int, value: str) -> dict: ...
